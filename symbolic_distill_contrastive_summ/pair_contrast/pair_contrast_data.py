def load_jsonl(filename):
    records = []
    with open(filename, 'r') as file:
        for line in file:
            records.append(json.loads(line))
    return records


class ContrastiveDataset(Dataset):
    # TODO: include reference summary in the collection of "positive summaries"
    def __init__(self, filename, tokenizer, max_src_len=512, max_tgt_len=128, source_prefix='',
                 use_original_ref=True, n_contrast_pair=1, is_decoder_only=False, prompt_path='prompt_formatted.json'):
        if filename.endswith('.jsonl'):
            self.data = load_jsonl(filename)
        else:
            self.data = json.load(open(filename, 'r', encoding='utf-8'))
        self.src_max_len = max_src_len
        self.tgt_max_len = max_tgt_len
        self.tokenizer = tokenizer
        self.use_original_ref = use_original_ref
        self.n_contrast_pair = n_contrast_pair

        # for each dialogue, we have a reference summary, a list of (positive_summary, negative_summary) pairs.
        # positive summaries and negative summaries are generated by ChatGPT
        self.dataset = []
        cur_instance = 0

        prompt_path = pathlib.Path(__file__).parent.parent.parent / f'generate_dataset/{prompt_path}'

        with open(prompt_path, "r") as f:
            try:
                data = json.loads(f.read())
                instruct = data["prompt_positive"]
            except Exception as e:
                print(f"Failed to load prompt !!! {e}")
                instruct = "Summarize the following dialogue:\n"

        if is_decoder_only:
            source_prefix = instruct
        
        for record in self.data:
            dialogue = source_prefix + record['dialogue']
            tokenized_source = tokenizer(dialogue, truncation=True, max_length=max_src_len)
            tokenized_source = {'input_ids': tokenized_source.input_ids,
                                'attention_mask': tokenized_source.attention_mask}
            ref_summ = record['summary']
            augmented_summaries = record['summaries']
            pos_summaries = [x['pos'] for x in augmented_summaries]
            neg_summaries = [x['neg'] for x in augmented_summaries]

            tokenized_pos_summs = tokenizer(pos_summaries, truncation=True, max_length=max_tgt_len)['input_ids']
            tokenized_neg_summs = tokenizer(neg_summaries, truncation=True, max_length=max_tgt_len)['input_ids']
            tokenized_ref = tokenizer(ref_summ, truncation=True, max_length=max_tgt_len)['input_ids']

            n_pos = len(pos_summaries)
            if self.use_original_ref:
                # the last element in 'pos_samples' will be used as target for cross entropy loss.
                # here each positive summary has a chance to act as the target for cross entropy loss.
                # the original human-written reference summary is always included in the positive pool
                for i in range(n_pos):
                    pos_samples = tokenized_pos_summs[:i] + tokenized_pos_summs[i+1:] + [tokenized_ref]
                    if self.n_contrast_pair - 1 > 0:
                        pos_samples = random.sample(pos_samples, self.n_contrast_pair - 1) + [tokenized_pos_summs[i]]

                    else:
                        pos_samples = [tokenized_pos_summs[i]]
                    neg_samples = random.sample(tokenized_neg_summs, self.n_contrast_pair)

                    self.dataset.append({
                        'source': tokenized_source,
                        # 'pos_samples': tokenized_pos_summs + [tokenized_ref],
                        'pos_samples': pos_samples,
                        'neg_samples': neg_samples,
                    })
                cur_instance += 1

                # if self.n_contrast_pair - 1 > 0:
                #     pos_samples = random.sample(tokenized_pos_summs, self.n_contrast_pair - 1)
                # else:
                #     pos_samples = []
                # self.dataset.append({
                #     'source': tokenized_source,
                #     'pos_samples': pos_samples + [tokenized_ref],
                #     'neg_samples': random.sample(tokenized_neg_summs, self.n_contrast_pair),
                # })
                # cur_instance += 1
            else:
                # the last element in 'pos_samples' will be used as target for cross entropy loss
                # only use ChatGPT generated positive summaries as target for cross entropy loss
                # also exclude the original human-written reference summary from positive pool
                for i in range(n_pos):
                    self.dataset.append({
                        'source': tokenized_source,
                        'pos_samples': tokenized_pos_summs[:i] + tokenized_pos_summs[i+1:] + [tokenized_pos_summs[i]],
                        'neg_samples': tokenized_neg_summs
                    })

    def __len__(self):
        return len(self.dataset)

    def __getitem__(self, idx):
        record = self.dataset[idx]
        return record


@dataclass
class DataCollatorForContrastive:
    tokenizer: Any
    model: Any = None
    padding: Union[bool, str] = True
    max_length: Optional[int] = None
    max_tgt: Optional[int] = None
    pad_to_multiple_of: Optional[int] = None
    label_pad_token_id: int = -100
    is_decoder_only: bool = True
    
    def __call__(self, features: List[Dict[str, Any]]) -> Dict[str, Any]:
        # Tentukan separator (biasanya EOS atau SEP token)
        sep_token_id = self.tokenizer.sep_token_id if self.tokenizer.sep_token_id is not None else self.tokenizer.eos_token_id
        
        final_inputs = [] # Untuk decoder-only (input+target) atau encoder-decoder (input saja)
        final_labels = [] 
        final_attention_mask = []
        src_select_indices = []
        cross_entropy_pos = []
        positive_contrast_pos = []
        valid_contrast_pos = []
        
        accumulate = 0

        max_length = self.max_length
        max_tgt = self.max_tgt
        tokenizer = self.tokenizer
        
        for i, feature in enumerate(features):
            source_ids = feature['source']['input_ids']
            valid_i = [] # Positif
            valid_j = [] # Semua (Positif + Negatif)

            # Gabungkan sampel Positif dan Negatif
            all_samples = [
                (feature['pos_samples'], True), 
                (feature['neg_samples'], False)
            ]

            for samples, is_positive in all_samples:
                for target_ids in samples:
                    src_select_indices.append(i)
                    
                    if self.is_decoder_only:
                        # # --- DECODER ONLY LOGIC ---
                        # # Format: [Input] + [Sep] + [Target]
                        # input_ids = source_ids + [sep_token_id] + target_ids
                        # # Masking: [-100] untuk Input & Sep, [Target] tetap ID asli
                        # mask_length = len(source_ids) + 1
                        # label_ids = [self.label_pad_token_id] * mask_length + target_ids
                        
                        # final_inputs.append({"input_ids": input_ids})
                        # final_labels.append(label_ids)
                        num_pad_src = max_length - len(source_ids)
                        src_block = ([tokenizer.pad_token_id] * num_pad_src) + source_ids
                        src_mask = ([0] * num_pad_src) + ([1] * len(source_ids))
                    
                        # B. Output Block: Right Padding
                        # [Summary, EOS, PAD, PAD, ...]
                        num_pad_tgt = max_tgt - len(target_ids)
                        tgt_block = target_ids+ ([tokenizer.pad_token_id] * num_pad_tgt)
                        tgt_mask = ([1] * len(target_ids)) + ([0] * num_pad_tgt)
                    
                        # --- PENGGABUNGAN ---
                    
                        # Gabungkan menjadi satu sequence utuh
                        input_ids = src_block + tgt_block
                        attention_mask = src_mask + tgt_mask
                        
                        # Labels: Seluruh blok input adalah -100, 
                        # di blok output hanya Summary yang asli, sisanya (pad) adalah -100
                        labels = ([-100] * max_length) + target_ids + ([-100] * num_pad_tgt)
                        final_inputs.append({'input_ids' : input_ids})
                        final_labels.append(labels)
                        final_attention_mask.append(attention_mask)
                    else:
                        # --- ENCODER-DECODER LOGIC ---
                        # Input dan Label dipisah
                        final_inputs.append({"input_ids": source_ids})
                        final_labels.append(target_ids)

                    if is_positive:
                        valid_i.append(accumulate)
                    
                    valid_j.append(accumulate)
                    accumulate += 1

                if is_positive:
                    # Ambil sampel positif terakhir sebagai referensi Cross Entropy
                    cross_entropy_pos.append(accumulate - 1)

            # Generate kombinasi untuk contrastive loss
            positive_contrast_pos.extend(list(itertools.combinations(valid_i, 2)))
            valid_contrast_pos.extend(list(itertools.combinations(valid_j, 2)))

        # --- PADDING LOGIC ---
        # 1. Pad Input (input_ids & attention_mask)
        batch = self.tokenizer.pad(
            final_inputs,
            padding=self.padding,
            max_length=self.max_length,
            pad_to_multiple_of=self.pad_to_multiple_of,
            return_tensors="pt",
        )

        if self.is_decoder_only:
            batch['attention_mask'] = torch.tensor(final_attention_mask, dtype=torch.long)
            batch['labels'] = torch.tensor(final_labels, dtype=torch.long)
        else:
            # 2. Pad Labels secara manual
            max_label_len = max(len(l) for l in final_labels)
            padded_labels = []
            for l in final_labels:
                remainder = [self.label_pad_token_id] * (max_label_len - len(l))
                if self.tokenizer.padding_side == "right":
                    padded_labels.append(l + remainder)
                else:
                    padded_labels.append(remainder + l)
            
            batch["labels"] = torch.tensor(padded_labels, dtype=torch.long)
        # print(batch)

        # --- CONTRASTIVE MATRIX CONSTRUCTION ---
        num_targets = len(final_labels)
        positive_contrast = torch.zeros((num_targets, num_targets), dtype=torch.bool)
        valid_contrast = torch.zeros((num_targets, num_targets), dtype=torch.bool)

        for a, b in positive_contrast_pos:
            positive_contrast[a, b] = positive_contrast[b, a] = True
        for a, b in valid_contrast_pos:
            valid_contrast[a, b] = valid_contrast[b, a] = True

        # Tambahkan metadata lainnya
        batch['src_select_indices'] = torch.tensor(src_select_indices, dtype=torch.long)
        batch['ce_pos'] = torch.tensor(cross_entropy_pos, dtype=torch.long)
        batch['positive_contrast'] = positive_contrast
        batch['valid_contrast'] = valid_contrast

        # Prepare decoder_input_ids (Hanya untuk Encoder-Decoder)
        if not self.is_decoder_only and self.model is not None:
            if hasattr(self.model, "prepare_decoder_input_ids_from_labels"):
                batch["decoder_input_ids"] = self.model.prepare_decoder_input_ids_from_labels(labels=batch["labels"])
        return batch